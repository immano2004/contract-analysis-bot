EMPLOYMENT_CONTRACT_TEMPLATE = """
EMPLOYMENT AGREEMENT

This Employment Agreement ("Agreement") is entered into on [DATE] between:

EMPLOYER: [COMPANY NAME]
Address: [COMPANY ADDRESS]
("Employer")

AND

EMPLOYEE: [EMPLOYEE NAME]
Address: [EMPLOYEE ADDRESS]
("Employee")

WHEREAS, the Employer wishes to employ the Employee, and the Employee wishes to be employed by the Employer, on the terms and conditions set forth herein;

NOW, THEREFORE, in consideration of the mutual covenants and agreements contained herein, the parties agree as follows:

1. EMPLOYMENT
The Employer hereby employs the Employee, and the Employee hereby accepts employment with the Employer, upon the terms and conditions of this Agreement.

2. POSITION AND DUTIES
The Employee shall hold the position of [JOB TITLE] and shall perform all duties and responsibilities as assigned by the Employer.

3. TERM
The employment under this Agreement shall commence on [START DATE] and shall continue for a period of [DURATION] unless terminated earlier in accordance with the terms of this Agreement.

4. COMPENSATION
4.1 The Employer shall pay the Employee a monthly salary of Rs. [AMOUNT] payable on the [DATE] of each month.
4.2 The Employee shall be entitled to annual increments based on performance.
4.3 The Employer shall provide [BENEFITS] as per company policy.

5. WORKING HOURS
5.1 The Employee shall work [NUMBER] hours per week.
5.2 Working hours shall be from [TIME] to [TIME] with a lunch break of [DURATION].
5.3 Overtime, if required, shall be compensated at 1.5 times the regular hourly rate.

6. LEAVE AND HOLIDAYS
6.1 The Employee shall be entitled to:
   - [NUMBER] days annual leave
   - [NUMBER] sick leave days
   - [NUMBER] casual leave days
   - Public holidays as per Indian law
6.2 Leave must be requested and approved in advance.

7. CONFIDENTIALITY
The Employee agrees to maintain confidentiality of all proprietary and confidential information obtained during employment.

8. INTELLECTUAL PROPERTY
All work product, inventions, and intellectual property created by the Employee during employment shall be the sole property of the Employer.

9. NON-COMPETE
During the term of employment and for [PERIOD] after termination, the Employee shall not engage in any business that competes with the Employer.

10. TERMINATION
10.1 The Employer may terminate this employment for:
   - Breach of contract
   - Misconduct
   - Poor performance
   - Redundancy
10.2 The Employee shall receive [NOTICE PERIOD] days notice or pay in lieu.
10.3 Gratuity shall be payable as per applicable law.

11. DISPUTE RESOLUTION
Any dispute arising from this Agreement shall be resolved through:
11.1 Mutual discussion
11.2 Mediation
11.3 Arbitration under the Arbitration and Conciliation Act, 1996

12. GOVERNING LAW
This Agreement shall be governed by the laws of India and subject to the jurisdiction of [JURISDICTION] courts.

IN WITNESS WHEREOF, the parties have executed this Agreement as of the date first written above.

For [COMPANY NAME]:

_________________________
Authorized Signatory
Name: [NAME]
Date: [DATE]


Employee:

_________________________
[EMPLOYEE NAME]
Date: [DATE]
"""

